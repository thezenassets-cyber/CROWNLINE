const CATALOGS: Record<Lang, Dict> = { en, fr, es, ar, zh };

export function isLang(value: string | undefined): value is Lang {
  return !!value && (LANGS as readonly string[]).includes(value);
}

export function textDir(lang: Lang): 'ltr' | 'rtl' {
  return DIR[lang];
}

export function translate(lang: Lang, key: string, fallback: string): string {
  return CATALOGS[lang][key] ?? CATALOGS.en[key] ?? fallback;
}

export interface PublicPrefs {
  lang: Lang;
  theme: Theme;
}

export function readPrefs(req: Request): PublicPrefs {
  const cookies = parseCookies(req.headers.cookie);
  return {
    lang: isLang(cookies.lang) ? cookies.lang : 'en',
    theme: cookies.theme === 'dark' ? 'dark' : 'light',
  };
}

export function safeNext(value: unknown, fallback = '/'): string {
  if (typeof value !== 'string') return fallback;
  if (!value.startsWith('/') || value.startsWith('//') || value.includes('\\') || value.includes('\n') || value.includes('\r')) return fallback;
  return value.slice(0, 240);
}
